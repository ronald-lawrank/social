"""Running the studio from any AI agent, not only Claude: the `lr` command in ~/.lawrank-studio/bin, the AGENTS.md
that Codex (and other agents) read from the shared Drive folder, and `lr docs` for the reference guides.

AGENTS.md is generated from SKILL.md, so Claude and Codex always follow the same instructions."""
import json
import os
import re
import stat
import sys
from pathlib import Path

from . import paths
from .util import LRError, write_text

REPO = "ronald-lawrank/social"
INSTALL_MAC = f"curl -fsSL https://raw.githubusercontent.com/{REPO}/main/install.sh | sh"
INSTALL_WIN = f"irm https://raw.githubusercontent.com/{REPO}/main/install.ps1 | iex"


def version() -> str:
    f = paths.SKILL.parent.parent / ".claude-plugin" / "plugin.json"
    try:
        return json.loads(f.read_text())["version"]
    except Exception:
        return "unknown"


def install_launcher() -> Path:
    """~/.lawrank-studio/bin/lr (and lr.cmd on Windows). It runs the copy installed by install.sh / install.ps1
    (~/.lawrank-studio/app, kept current by `lr update`) when there is one, else this copy."""
    paths.BIN.mkdir(parents=True, exist_ok=True)
    app_lr = paths.STATE / "app" / "plugin" / "skills" / "lawrank-studio" / "scripts" / "lr.py"
    lr_py = app_lr if app_lr.exists() else paths.SCRIPTS / "lr.py"
    venv_py = paths.STATE / "venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
    py = venv_py if venv_py.exists() else Path(sys.executable)
    if os.name == "nt":
        f = paths.BIN / "lr.cmd"
        write_text(f, f'@echo off\r\n"{py}" "{lr_py}" %*\r\n')
    else:
        f = paths.BIN / "lr"
        write_text(f, f'#!/bin/sh\n# LawRank Studio {version()}: runs the installed copy at {lr_py}\nexec "{py}" "{lr_py}" "$@"\n')
        f.chmod(f.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return f


def agents_md() -> str:
    """AGENTS.md for the shared Drive folder: the same instructions as SKILL.md, for agents without Claude skills."""
    skill = (paths.SKILL / "SKILL.md").read_text(encoding="utf-8")
    body = re.sub(r"\A---.*?---\s*", "", skill, flags=re.S)                     # drop the Claude skill header
    body = re.sub(r"reference/([a-z]+)\.md", r"`lr docs \1`", body)              # guides: printed by `lr docs <name>`
    # Claude runs the plugin's own copy; other agents run the `lr` command that setup creates
    body = re.sub(r"In this file `lr` means:\s*```\s*python3 \"<this skill's folder>/scripts/lr\.py\"\s*```",
                  lambda m: "In this file `lr` means `~/.lawrank-studio/bin/lr` (Windows: `%USERPROFILE%\\.lawrank-studio\\bin\\lr.cmd`).",
                  body)
    head = f"""<!-- Generated by `lr setup` from LawRank Studio {version()} (SKILL.md). Don't edit: changes are overwritten. -->
# LawRank Studio (instructions for AI agents working in this folder)

This shared folder is LawRank's social creative studio for law firms. Whenever someone asks for anything about a
LawRank client, a law firm's website, test designs, posts, carousels, videos or packages, follow the instructions
below.

**The `lr` command.** It's at `~/.lawrank-studio/bin/lr` (Windows: `%USERPROFILE%\\.lawrank-studio\\bin\\lr.cmd`).
If it isn't there, install the studio once (it needs the internet and permission to write to `~/.lawrank-studio`;
ask the person to approve both):
- Mac: `{INSTALL_MAC}`
- Windows (PowerShell): `{INSTALL_WIN}`

Keep it current with `lr update`. Read a reference guide with `lr docs <name>` (onboarding, writing, motion,
delivery) when the instructions say to.

---

"""
    return head + body


def write_agents_md(home: Path) -> Path | None:
    """Write AGENTS.md into the shared folder when it's missing or from an older version (no needless Drive syncs)."""
    f = Path(home) / "AGENTS.md"
    text = agents_md()
    if f.exists():
        current = f.read_text(encoding="utf-8")
        if current == text:
            return None
        m = re.search(r"LawRank Studio ([\d.]+) \(SKILL\.md\)", current)
        if m and _vtuple(m.group(1)) > _vtuple(version()):   # a laptop on an older version never downgrades it
            return None
    write_text(f, text)
    return f


def _vtuple(v: str) -> tuple:
    return tuple(int(x) for x in re.findall(r"\d+", v)) or (0,)


def docs(name: str) -> dict:
    """A reference guide, for agents that can't open the skill's files directly."""
    guides = sorted(p.stem for p in (paths.SKILL / "reference").glob("*.md"))
    if name not in guides:
        raise LRError(f"No guide called '{name}'", fix=f"Guides: {', '.join(guides)}")
    return {"ok": True, "guide": name, "text": (paths.SKILL / "reference" / f"{name}.md").read_text(encoding="utf-8")}


ARCHIVE = f"https://codeload.github.com/{REPO}/tar.gz/refs/heads/main"


def update() -> dict:
    """`lr update`: the newest studio from GitHub, for copies installed with install.sh / install.ps1 (in
    ~/.lawrank-studio/app). The Claude plugin updates through Claude instead."""
    import shutil
    import subprocess
    import tarfile
    import tempfile
    app = paths.STATE / "app"
    if app.resolve() not in paths.SKILL.resolve().parents:
        return {"ok": True, "updated": False, "version": version(),
                "note": "This copy is the Claude plugin: update it in Claude with `/plugin marketplace update lawrank`, then run `lr setup`."}
    src = os.environ.get("LR_ARCHIVE") or ARCHIVE
    tmp = Path(tempfile.mkdtemp(prefix="lr-update-"))
    try:
        tgz = tmp / "studio.tgz"
        if Path(src).exists():
            shutil.copy(src, tgz)
        else:
            from .util import fetch
            tgz.write_bytes(fetch(src, timeout=120))
        out = tmp / "x"
        with tarfile.open(tgz) as t:
            try:
                t.extractall(out, filter="data")          # refuses absolute paths and links outside the folder
            except TypeError:
                t.extractall(out)
        new = next(p for p in out.iterdir() if p.is_dir())
        if not (new / "plugin" / "skills" / "lawrank-studio" / "scripts" / "lr.py").exists():
            raise LRError("The download didn't contain LawRank Studio", fix="Try `lr update` again later.")
        old_version = version()
        shutil.rmtree(paths.STATE / "app.old", ignore_errors=True)
        app.rename(paths.STATE / "app.old")
        shutil.move(str(new), str(app))
        shutil.rmtree(paths.STATE / "app.old", ignore_errors=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    lr_py = app / "plugin" / "skills" / "lawrank-studio" / "scripts" / "lr.py"
    r = subprocess.run([sys.executable, str(lr_py), "setup"], capture_output=True, text=True)
    res = json.loads((r.stdout.strip().splitlines() or ["{}"])[-1] or "{}")
    return {"ok": bool(res.get("ok", r.returncode == 0)), "updated": True, "from": old_version,
            "to": json.loads((app / "plugin" / ".claude-plugin" / "plugin.json").read_text())["version"],
            "setup": {k: res[k] for k in ("installed", "warnings", "failed_steps", "missing", "fix") if k in res}}

